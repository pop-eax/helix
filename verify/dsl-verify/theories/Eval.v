(** * Computable Evaluator for the Helix DSL

    This file provides a fuel-based computable evaluator that mirrors the
    big-step inductive relations in [Semantics.v].  It is used for:
    - Differential testing against the Rust compiler pipeline
    - Extraction to OCaml for the fuzzing oracle

    All functions return [None] to represent stuck evaluation (undefined
    behavior, division by zero, out-of-scope variables, etc.).

    [fuel] is a [nat] used to ensure termination.  For any program
    generated by the bounded fuzzer, [fuel = 10000] suffices. *)

(* ------------------------------------------------------------------ *)
(** ** Evaluate a list of expressions *)

(** Helper: fold a list of [option value] to [option (list value)]. *)
Definition collect_opts {A : Type} (xs : list (option A)) : option (list A) :=
  List.fold_right
    (fun mx acc =>
       match mx, acc with
       | Some x, Some ys => Some (x :: ys)
       | _, _ => None
       end)
    (Some []) xs.

(* ------------------------------------------------------------------ *)
(** ** Mutually recursive computable evaluator *)

(** [eval_expr_c fuel Φ ρ e] evaluates expression [e] in function
    environment [Φ] and variable environment [ρ], returning [None] on
    any stuck state. *)
Fixpoint eval_expr_c (fuel : nat) (Φ : func_val_env) (ρ : val_env) (e : expr)
    {struct fuel} : option value :=
  match fuel with
  | O      => None
  | S fuel' =>
    match e with
    | EVar x => val_lookup ρ x

    | EConst v => Some v

    | EBinop op e1 e2 =>
        match eval_expr_c fuel' Φ ρ e1 with
        | None    => None
        | Some v1 =>
          match eval_expr_c fuel' Φ ρ e2 with
          | None    => None
          | Some v2 => eval_binop op v1 v2
          end
        end

    | EUnop op e1 =>
        match eval_expr_c fuel' Φ ρ e1 with
        | None    => None
        | Some v1 => eval_unop op v1
        end

    | ESelect ec et ee =>
        match eval_expr_c fuel' Φ ρ ec with
        | Some (VBool true)  => eval_expr_c fuel' Φ ρ et
        | Some (VBool false) => eval_expr_c fuel' Φ ρ ee
        | _                  => None
        end

    | EIndex earr i =>
        match eval_expr_c fuel' Φ ρ earr with
        | Some (VArray _ vs) => nth_error vs i
        | _                  => None
        end

    | EField estruct fname =>
        match eval_expr_c fuel' Φ ρ estruct with
        | Some (VStruct _ fs) =>
            match List.find (fun p => String.eqb (fst p) fname) fs with
            | Some (_, v) => Some v
            | None        => None
            end
        | _ => None
        end

    | ECall f args =>
        match func_val_lookup Φ f with
        | None     => None
        | Some fv  =>
          match eval_exprs_c fuel' Φ ρ args with
          | None      => None
          | Some vals =>
            if Nat.eqb (List.length (fv_params fv)) (List.length vals) then
              let bound := List.combine (fv_params fv) vals in
              match eval_stmts_c fuel' Φ bound (fv_body fv) with
              | Some (ReturnVal v) => Some v
              | _                  => None
              end
            else None
          end
        end
    end
  end

(** [eval_exprs_c fuel Φ ρ es] evaluates a list of expressions left-to-right,
    returning [None] if any evaluation fails. *)
with eval_exprs_c (fuel : nat) (Φ : func_val_env) (ρ : val_env) (es : list expr)
    {struct fuel} : option (list value) :=
  match fuel with
  | O      => None
  | S fuel' =>
    match es with
    | []       => Some []
    | e :: rest =>
      match eval_expr_c fuel' Φ ρ e with
      | None   => None
      | Some v =>
        match eval_exprs_c fuel' Φ ρ rest with
        | None     => None
        | Some vs  => Some (v :: vs)
        end
      end
    end
  end

(** [eval_stmt_c fuel Φ ρ s] evaluates a single statement. *)
with eval_stmt_c (fuel : nat) (Φ : func_val_env) (ρ : val_env) (s : stmt)
    {struct fuel} : option eval_result :=
  match fuel with
  | O      => None
  | S fuel' =>
    match s with
    | SLet _vis _ty x e =>
        match eval_expr_c fuel' Φ ρ e with
        | None   => None
        | Some v => Some (Continue (val_update ρ x v))
        end

    | SAssign x e =>
        match eval_expr_c fuel' Φ ρ e with
        | None   => None
        | Some v => Some (Continue (val_update ρ x v))
        end

    | SIf ec sthen selse =>
        match eval_expr_c fuel' Φ ρ ec with
        | Some (VBool true)  => eval_stmts_c fuel' Φ ρ sthen
        | Some (VBool false) => eval_stmts_c fuel' Φ ρ selse
        | _                  => None
        end

    | SReturn e =>
        match eval_expr_c fuel' Φ ρ e with
        | None   => None
        | Some v => Some (ReturnVal v)
        end

    | SFor x lo hi body =>
        eval_for_c fuel' Φ ρ x lo hi body
    end
  end

(** [eval_stmts_c fuel Φ ρ ss] evaluates a list of statements sequentially,
    threading the environment and short-circuiting on [return]. *)
with eval_stmts_c (fuel : nat) (Φ : func_val_env) (ρ : val_env) (ss : list stmt)
    {struct fuel} : option eval_result :=
  match fuel with
  | O      => None
  | S fuel' =>
    match ss with
    | []       => Some (Continue ρ)
    | s :: rest =>
      match eval_stmt_c fuel' Φ ρ s with
      | None                 => None
      | Some (ReturnVal v)   => Some (ReturnVal v)
      | Some (Continue ρ')   => eval_stmts_c fuel' Φ ρ' rest
      end
    end
  end

(** [eval_for_c fuel Φ ρ x lo hi body] unrolls a for loop [for x in lo..hi]. *)
with eval_for_c (fuel : nat) (Φ : func_val_env) (ρ : val_env)
    (x : string) (lo hi : nat) (body : list stmt) {struct fuel} : option eval_result :=
  match fuel with
  | O      => None
  | S fuel' =>
    if Nat.leb hi lo then Some (Continue ρ)
    else
      let v := VField 64%nat (to_field 64%nat (Z.of_nat lo)) in
      match eval_stmts_c fuel' Φ (val_update ρ x v) body with
      | None                 => None
      | Some (ReturnVal v)   => Some (ReturnVal v)
      | Some (Continue ρ')   => eval_for_c fuel' Φ ρ' x (S lo) hi body
      end
  end.

(* ------------------------------------------------------------------ *)
(** ** Top-level entry point *)

(** [eval_program_c fuel p inputs] evaluates program [p] with the given
    input bindings, looking for the function named ["main"].
    Returns [None] if no main function exists or evaluation gets stuck. *)
Definition eval_program_c (fuel : nat) (p : program) (inputs : val_env)
    : option value :=
  let Φ := func_val_env_of p in
  match List.find (fun fd => String.eqb (fd_name fd) "main") (prog_funcs p) with
  | None    => None
  | Some fd =>
      match eval_stmts_c fuel Φ inputs (fd_body fd) with
      | Some (ReturnVal v) => Some v
      | _                  => None
      end
  end.
